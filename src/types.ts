// Base configuration interface
export interface USAiConfig {
  apiKey: string;
  baseUrl: string;
  timeout?: number;
  maxRetries?: number;
  retryDelay?: number;
  /**
   * When true, the client spaces out requests to stay within the documented
   * per-key rate limits (models: 3/s, chat completions: 3/s, embeddings: 100/s).
   * Limits are tracked per client instance only. Defaults to false.
   */
  throttleRequests?: boolean;
}

/**
 * Documented per-API-key rate limits (requests per second) by endpoint
 * @see https://www.usai.gov/api-documentation/
 */
export const USAiRateLimits: Readonly<Record<string, number>> = {
  '/api/v1/models': 3,
  '/api/v1/chat/completions': 3,
  '/api/v1/embeddings': 100,
};

// Model information
export interface Model {
  id: string;
  object: 'model';
  created: number;
  owned_by: string;
  permission?: Array<{
    id: string;
    object: string;
    created: number;
    allow_create_engine: boolean;
    allow_sampling: boolean;
    allow_logprobs: boolean;
    allow_search_indices: boolean;
    allow_view: boolean;
    allow_fine_tuning: boolean;
    organization: string;
    group: string | null;
    is_blocking: boolean;
  }>;
  root?: string;
  parent?: string | null;
}

export interface ModelsResponse {
  object: 'list';
  data: Model[];
}

// Chat completion types
export interface ChatMessageContentPart {
  type: 'text' | 'image_url' | 'file';
  text?: string;
  image_url?: {
    url: string;
    detail?: 'low' | 'high' | 'auto';
  };
  file_name?: string;
  file?: {
    file_data: string;
  };
}

/**
 * A function the model may ask the caller to invoke
 */
export interface FunctionDefinition {
  name: string;
  description?: string;
  /** JSON Schema describing the function's parameters */
  parameters?: Record<string, unknown>;
}

/**
 * A tool made available to the model in a chat completion request
 */
export interface ChatCompletionTool {
  type: 'function';
  function: FunctionDefinition;
}

/**
 * Controls whether and which tool the model calls
 */
export type ChatCompletionToolChoice =
  | 'none'
  | 'auto'
  | 'required'
  | { type: 'function'; function: { name: string } };

/**
 * A tool call requested by the model
 */
export interface ChatCompletionMessageToolCall {
  id: string;
  type: 'function';
  function: {
    name: string;
    /** JSON-encoded arguments generated by the model */
    arguments: string;
  };
}

export interface ChatMessage {
  role: 'system' | 'user' | 'assistant' | 'tool';
  /** May be null or omitted for assistant messages that only contain tool calls */
  content?: string | ChatMessageContentPart[] | null;
  name?: string;
  /** Tool calls requested by the model (assistant messages) */
  tool_calls?: ChatCompletionMessageToolCall[];
  /** ID of the tool call this message responds to (tool messages) */
  tool_call_id?: string;
}

export interface ChatCompletionRequest {
  model: string;
  messages: ChatMessage[];
  tools?: ChatCompletionTool[];
  tool_choice?: ChatCompletionToolChoice;
  /** Response creativity (0.0-1.0) */
  temperature?: number;
  top_p?: number;
  max_tokens?: number;
  stream?: boolean;
  stop?: string | string[];
  presence_penalty?: number;
  frequency_penalty?: number;
  logit_bias?: Record<string, number>;
  user?: string;
}

export interface ChatCompletionChoice {
  index: number;
  message: ChatMessage;
  finish_reason: 'stop' | 'length' | 'content_filter' | 'tool_calls' | null;
}

export interface ChatCompletionResponse {
  id: string;
  object: 'chat.completion';
  created: number;
  model: string;
  choices: ChatCompletionChoice[];
  usage: {
    prompt_tokens: number;
    completion_tokens: number;
    total_tokens: number;
  };
}

export interface ChatCompletionStreamChoice {
  index: number;
  delta: {
    role?: 'assistant';
    content?: string | null;
    tool_calls?: Array<{
      index: number;
      id?: string;
      type?: 'function';
      function?: {
        name?: string;
        arguments?: string;
      };
    }>;
  };
  finish_reason: 'stop' | 'length' | 'content_filter' | 'tool_calls' | null;
}

export interface ChatCompletionStreamResponse {
  id: string;
  object: 'chat.completion.chunk';
  created: number;
  model: string;
  choices: ChatCompletionStreamChoice[];
}

// Embeddings types
export interface EmbeddingRequest {
  model: string;
  input: string | string[];
  user?: string;
  input_type?:
    | 'search_document'
    | 'search_query'
    | 'clustering'
    | 'classification'
    | 'semantic_similarity';
  /** Number of dimensions for the output embeddings. Only supported by some models. */
  dimensions?: number;
  /** Encoding format, using the field name shown in the USAi API documentation */
  encodingFormat?: 'float' | 'int8' | 'uint8' | 'binary' | 'ubinary';
  /** OpenAI-style alias for `encodingFormat` */
  encoding_format?: 'float' | 'int8' | 'uint8' | 'binary' | 'ubinary';
  truncate?: 'NONE' | 'START' | 'END';
}

export interface EmbeddingObject {
  object: 'embedding';
  embedding: number[];
  index: number;
}

export interface EmbeddingResponse {
  object: 'list';
  data: EmbeddingObject[];
  model: string;
  /**
   * Token usage. The API returns camelCase fields (`promptTokens`, `totalTokens`);
   * the client also populates the OpenAI-style snake_case fields.
   */
  usage: {
    prompt_tokens: number;
    total_tokens: number;
    promptTokens?: number;
    totalTokens?: number;
  };
}

// Error types
export interface USAiError {
  error: {
    message: string;
    type?: string | null;
    param?: string | null;
    code?: string | null;
  };
}

// Rate limiting
export interface RateLimitInfo {
  remaining: number;
  reset: number;
  limit: number;
}
